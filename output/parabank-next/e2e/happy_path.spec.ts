// Legacy2Next가 happy_paths.json 에서 결정적으로 생성한 흐름 검증입니다.
import { expect, test } from '@playwright/test'

test('hp1 계좌 잔액 및 거래 내역 조회', async ({ page }) => {
  await page.goto('/login?next=/overview')
  // hp1-s1 로그인 (홈) (login)
  await expect(page.getByTestId('index-page')).toBeVisible()
  await page.getByTestId('index-field-username').fill('demo')
  await page.getByTestId('index-field-password').fill('demo')
  await page.getByTestId('index-submit').first().click()
  // hp1-s2 계좌 개요 (view)
  await expect(page.getByTestId('overview-page')).toBeVisible()
  await page.getByTestId('overview-to-activity').first().click()
  // hp1-s3 계좌 활동 내역 (view)
  await expect(page.getByTestId('activity-page')).toBeVisible()
  await page.getByTestId('activity-to-transaction').first().click()
  // hp1-s4 거래 상세 (view)
  await expect(page.getByTestId('transaction-page')).toBeVisible()
})

test('hp2 계좌 간 자금 이체', async ({ page }) => {
  await page.goto('/login?next=/overview')
  // hp2-s1 로그인 (홈) (login)
  await expect(page.getByTestId('index-page')).toBeVisible()
  await page.getByTestId('index-field-username').fill('demo')
  await page.getByTestId('index-field-password').fill('demo')
  await page.getByTestId('index-submit').first().click()
  // hp2-s2 계좌 개요 (navigate)
  await expect(page.getByTestId('overview-page')).toBeVisible()
  await page.getByTestId('overview-to-transfer').first().click()
  // hp2-s3 자금 이체 (fill_submit)
  await expect(page.getByTestId('transfer-page')).toBeVisible()
  await page.getByTestId('transfer-field-input').fill('1')
  await page.getByTestId('transfer-field-fromaccountid').click()
  await page.locator('.ant-select-dropdown:not(.ant-select-dropdown-hidden)').last().locator('.ant-select-item-option').first().click()
  await page.getByTestId('transfer-field-toaccountid').click()
  await page.locator('.ant-select-dropdown:not(.ant-select-dropdown-hidden)').last().locator('.ant-select-item-option').first().click()
  await page.getByTestId('transfer-submit').first().click()
  const ok = page.locator('.ant-modal:visible .ant-btn-primary')
  if (await ok.count()) await ok.first().click()
  // hp2-s4 자금 이체 결과 (view)
  await expect(page.getByTestId('transferResult-page')).toBeVisible()
  await expect(page.getByText('완료').first()).toBeVisible()
})
